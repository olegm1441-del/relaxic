const clamp = (n, lo, hi) => Math.min(hi, Math.max(lo, n));

/** Разворачиваем сюжеты в SKU: сюжет × техника */
export function buildProducts() {
  const out = [];
  for (const art of ARTWORKS) {
    for (const [i, key] of art.techniques.entries()) {
      const tech = TECHNIQUES.find((t) => t.key === key);
      const eff = EFFORT_BY_TECHNIQUE[key];
      const pricing = PRICE_BY_TECHNIQUE[key];
      const difficulty = clamp(art.base.difficulty + eff.difficulty, 1, 5);
      const price = clamp(
        pricing.base + pricing.perDifficulty * (difficulty - 3),
        80000,
        150000,
      );
      out.push({
        slug: `${art.slug}-${tech.suffix}`,
        artwork: art.slug,
        title: art.title,
        fullTitle: `${art.title} — ${tech.one.toLowerCase()}`,
        fandom: art.fandom,
        technique: key,
        price,
        // Старая цена только у первого исполнения: скидка на всё — это не скидка
        oldPrice: i === 0 && art.hit ? Math.round((price * 1.25) / 1000) * 1000 : null,
        difficulty,
        hours: Math.round(art.base.hours * eff.hours),
        colorsCount: Math.round(art.base.colors * eff.colors),
        minAge: art.base.minAge,
        isHit: Boolean(art.hit) && i === 0,
        isNew: i > 0,
        lead: art.lead,
        story: art.story,
        images: [1, 2, 3].map((n) => ({
          url: `/img/product/${art.slug}-${n}.jpg`,
          alt: `${art.title} — ${tech.one.toLowerCase()}, фото ${n}`,
        })),
        boxContents: BOX_CONTENTS[key],
        specs: SPECS[key],
        seoTitle: `${art.title} — ${tech.one.toLowerCase()} · Relaxic`,
        seoDescription: `${art.lead} ${tech.one} по вселенной «${
          FANDOMS.find((f) => f.slug === art.fandom)?.title ?? ""
        }». Доставка по всей России.`,
      });
    }
  }
  return out;
}

