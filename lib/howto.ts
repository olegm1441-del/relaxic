/** Адреса разборов по-английски — так их проще ставить в рекламу и цитировать */
export const HOWTO_SLUG: Record<TechniqueKey, string> = {
  PAINT_BY_NUMBERS: "paint-by-numbers",
  DIAMOND_MOSAIC: "diamond-mosaic",
  CROSS_STITCH: "cross-stitch",
};

export function techniqueByHowto(slug: string): Technique | undefined {
  const key = (Object.keys(HOWTO_SLUG) as TechniqueKey[]).find((k) => HOWTO_SLUG[k] === slug);
  return key ? TECHNIQUES.find((t) => t.key === key) : undefined;
}

